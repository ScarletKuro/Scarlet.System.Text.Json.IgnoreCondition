using System.Collections.Generic;
using System.Text;

namespace Scarlet.Text.Json.SourceGeneration;

/// <summary>Renders the per-assembly registry class.</summary>
internal static class Emitter
{
    public static string Emit(
        IReadOnlyList<TypeRegistration> registrations,
        bool emitModuleInitializer,
        string generatorVersion)
    {
        var source = new StringBuilder();

        source.AppendLine("// <auto-generated/>");
        source.AppendLine("#nullable enable");
        source.AppendLine();
        source.AppendLine("namespace Scarlet.Text.Json.SourceGeneration");
        source.AppendLine("{");
        source.AppendLine("    /// <summary>");
        source.AppendLine("    /// Registers the ignore conditions declared in this assembly, so that the library never has");
        source.AppendLine("    /// to read [JsonIgnoreEx] by reflection.");
        source.AppendLine("    /// </summary>");
        source.AppendLine($"    [global::System.CodeDom.Compiler.GeneratedCode(\"Scarlet.Text.Json.IgnoreCondition.SourceGeneration\", \"{generatorVersion}\")]");
        source.AppendLine("    [global::System.Diagnostics.CodeAnalysis.ExcludeFromCodeCoverage]");
        source.AppendLine("    internal static class ScarletIgnoreConditions");
        source.AppendLine("    {");
        source.AppendLine("        private static int _registered;");
        source.AppendLine();
        source.AppendLine("        /// <summary>Registers every annotated type in this assembly. Idempotent.</summary>");
        source.AppendLine("        internal static void Register()");
        source.AppendLine("        {");
        source.AppendLine("            if (global::System.Threading.Interlocked.Exchange(ref _registered, 1) != 0)");
        source.AppendLine("            {");
        source.AppendLine("                return;");
        source.AppendLine("            }");
        source.AppendLine();

        for (int i = 0; i < registrations.Count; i++)
        {
            TypeRegistration registration = registrations[i];
            source.AppendLine(
                $"            {JsonIgnoreConditionGenerator.RegistryName}.Register(" +
                $"typeof({registration.TypeExpression}), Configure_{registration.SafeName});");
        }

        source.AppendLine("        }");

        if (emitModuleInitializer)
        {
            source.AppendLine();
            source.AppendLine("        /// <summary>");
            source.AppendLine("        /// Runs before anything in this assembly can be used, which is early enough for the");
            source.AppendLine("        /// serializer to see the registrations when it first resolves a contract.");
            source.AppendLine("        /// </summary>");
            source.AppendLine("        [global::System.Runtime.CompilerServices.ModuleInitializer]");
            source.AppendLine("        internal static void Initialize() => Register();");
        }

        foreach (TypeRegistration registration in registrations)
        {
            source.AppendLine();
            source.AppendLine($"        private static void Configure_{registration.SafeName}({JsonIgnoreConditionGenerator.BuilderInterfaceName} builder)");
            source.AppendLine("        {");

            foreach (MemberRegistration member in registration.Members)
            {
                source.AppendLine($"            {member.BuilderCall}");
            }

            source.AppendLine("        }");
        }

        source.AppendLine("    }");
        source.AppendLine("}");

        return source.ToString();
    }
}
